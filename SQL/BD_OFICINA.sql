-- Questão 1
SELECT 
	CLIENTES.NOME, 
    COUNT(VEICULOS.ID) AS "QTD CARROS" 
FROM CLIENTES
INNER JOIN VEICULOS
ON CLIENTES.ID = VEICULOS.CLIENTE_ID
GROUP BY CLIENTES.ID, CLIENTES.NOME;


-- Questão 2

SELECT
	VEICULOS.ID,
    VEICULOS.PLACA,
    VEICULOS.MARCA,
    VEICULOS.MODELO,
    COUNT(AGENDAMENTOS.ID) AS "QTD AGENDAMENTOS"
FROM VEICULOS
INNER JOIN AGENDAMENTOS
	ON VEICULOS.ID = AGENDAMENTOS.VEICULO_ID
GROUP BY VEICULOS.ID;

-- Quastão 3

SELECT
	CLIENTES.NOME AS "NOME DO CLIENTE",
    COUNT(AGENDAMENTOS.ID) AS "QUANTIDADES DE AGENDAMENTOS"
FROM CLIENTES
LEFT JOIN VEICULOS
	ON CLIENTES.ID = VEICULOS.CLIENTE_ID
LEFT JOIN AGENDAMENTOS
	ON VEICULOS.ID = AGENDAMENTOS.VEICULO_ID
GROUP BY CLIENTES.ID, CLIENTES.NOME;